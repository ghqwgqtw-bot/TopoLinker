def looks_like_deepprotacs_repo(path: Path) -> bool:
    return (
        path.is_dir()
        and (path / "single_prediction.py").is_file()
        and (path / "model.py").is_file()
        and (path / "model" / "test.pt").is_file()
    )


def find_deepprotacs_repo(
    explicit: Optional[str],
    project_root: Path,
) -> Optional[Path]:
    candidates: List[Path] = []

    if explicit:
        candidates.append(resolve_user_path(explicit, project_root))

    env_dir = os.environ.get("DEEPPROTACS_DIR", "").strip()
    if env_dir:
        candidates.append(Path(env_dir).expanduser())

    candidates.extend([
        project_root / "DeepPROTACs",
        project_root.parent / "DeepPROTACs",
        Path.cwd() / "DeepPROTACs",
        Path.cwd().parent / "DeepPROTACs",
        Path(r"D:\pycharm\Pycharm_Projects\DeepPROTACs"),
        Path(r"D:\pycharm\Pycharm_Projects\DeepPROTACs-main"),
    ])

    seen = set()
    for c in candidates:
        try:
            c = c.resolve()
        except Exception:
            pass
        key = os.path.normcase(str(c))
        if key in seen:
            continue
        seen.add(key)
        if looks_like_deepprotacs_repo(c):
            return c

    return None


def validate_repo(repo: Path) -> Dict[str, Path]:
    files = {
        "single_prediction.py": repo / "single_prediction.py",
        "model.py": repo / "model.py",
        "model/test.pt": repo / "model" / "test.pt",
    }

    missing = [
        name
        for name, path in files.items()
        if not path.is_file()
    ]

    if missing:
        raise FileNotFoundError(
            "DeepPROTACs repository is incomplete. Missing: "
            + ", ".join(missing)
            + f"\nrepo={repo}"
        )

    return files


# =====================================================================
# Official MOL2 parser compatibility check
# =====================================================================

def inspect_mol2_for_official_parser(path: Path) -> Dict[str, Any]:
    """
    DeepPROTACs single_prediction.py uses a very simple MOL2 parser:
    everything after @<TRIPOS>BOND is interpreted as a bond line.

    We only inspect and report here; we do NOT modify chemical content.
    """
    text = safe_read_text(path)
    lines = text.splitlines()

    markers = [
        line.strip()
        for line in lines
        if line.strip().startswith("@<TRIPOS>")
    ]

    has_atom = "@<TRIPOS>ATOM" in markers
    has_bond = "@<TRIPOS>BOND" in markers

    trailing_sections = []
    if has_bond:
        bond_idx = next(
            i for i, line in enumerate(lines)
            if line.strip() == "@<TRIPOS>BOND"
        )
        for line in lines[bond_idx + 1:]:
            s = line.strip()
            if s.startswith("@<TRIPOS>"):
                trailing_sections.append(s)

    return {
        "markers": markers,
        "has_atom_section": has_atom,
        "has_bond_section": has_bond,
        "sections_after_bond": trailing_sections,
        "official_parser_compatible": bool(
            has_atom and has_bond and not trailing_sections
        ),
    }


