def get_nested(d: Dict[str, Any], *keys: str) -> Any:
    cur: Any = d
    for k in keys:
        if not isinstance(cur, dict) or k not in cur:
            raise KeyError(".".join(keys))
        cur = cur[k]
    return cur


def manifest_input_paths(
    manifest: Dict[str, Any],
    *,
    manifest_dir: Path,
) -> Dict[str, Path]:
    """
    Read the exact paths emitted by prepare_deepprotacs_pilot_sample.py.

    We accept absolute paths directly. Relative paths, if any, are resolved
    relative to the manifest directory.
    """
    raw = {
        "ligase_ligand.mol2": get_nested(
            manifest, "e3", "ligase_ligand_mol2"
        ),
        "ligase_pocket.mol2": get_nested(
            manifest, "e3", "ligase_pocket_mol2"
        ),
        "target_ligand.mol2": get_nested(
            manifest, "poi", "target_ligand_mol2"
        ),
        "target_pocket.mol2": get_nested(
            manifest, "poi", "target_pocket_mol2"
        ),
        "linker.smi": manifest.get("linker_smi_path"),
    }

    if not raw["linker.smi"]:
        # Conservative fallback for older manifests.
        raw["linker.smi"] = str(manifest_dir / "linker.smi")

    out: Dict[str, Path] = {}
    for name, value in raw.items():
        if value is None or str(value).strip() == "":
            raise RuntimeError(
                f"Manifest does not contain a usable path for {name}"
            )
        p = Path(str(value)).expanduser()
        if not p.is_absolute():
            p = (manifest_dir / p).resolve()
        else:
            p = p.resolve()
        out[name] = p

    return out


def validate_manifest_ready(manifest: Dict[str, Any]) -> None:
    if manifest.get("all_four_binary_mol2_ready") is False:
        raise RuntimeError(
            "pilot_sample.json says all_four_binary_mol2_ready=False. "
            "Re-run prepare_deepprotacs_pilot_sample.py after preparing "
            "the missing POI/E3 inputs."
        )

    poi = manifest.get("poi", {})
    e3 = manifest.get("e3", {})

    if isinstance(poi, dict) and poi.get("deep_inputs_ready") is False:
        raise RuntimeError("POI DeepPROTACs inputs are not ready.")

    if isinstance(e3, dict) and e3.get("deep_inputs_ready") is False:
        raise RuntimeError("E3 DeepPROTACs inputs are not ready.")


