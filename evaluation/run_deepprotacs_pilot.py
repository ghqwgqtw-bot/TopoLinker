def write_csv_result(path: Path, result: Dict[str, Any]) -> None:
    row = {
        "timestamp": result["timestamp"],
        "stage": result["sample"]["stage"],
        "record_index": result["sample"]["record_index"],
        "uuid": result["sample"]["uuid"],
        "sample_id": result["sample"]["sample_id"],
        "poi_pair_id": result["sample"]["poi_pair_id"],
        "e3_pair_id": result["sample"]["e3_pair_id"],
        "linker_smiles": result["sample"]["linker_smiles"],
        "prediction": result["prediction"],
        "prediction_label": result["prediction_label"],
        "predicted_active": int(result["predicted_active"]),
        "script_mode": result["script_mode"],
        "returncode": result["returncode"],
        "deepprotacs_repo": result["deepprotacs_repo"],
        "deepprotacs_python": result["deepprotacs_python"],
        "single_prediction_sha256": result["official_files"][
            "single_prediction.py"
        ]["sha256"],
        "model_test_pt_sha256": result["official_files"][
            "model/test.pt"
        ]["sha256"],
    }

    with path.open(
        "w",
        newline="",
        encoding="utf-8-sig",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=list(row.keys()),
        )
        writer.writeheader()
        writer.writerow(row)


