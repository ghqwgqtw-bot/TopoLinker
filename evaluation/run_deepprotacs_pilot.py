"""
Run ONE matched TopoLinker sample through the OFFICIAL DeepPROTACs
single-prediction pipeline.

Design principle
----------------
This wrapper does NOT reimplement DeepPROTACs graph construction, atom
vocabulary, linker SMILES encoding, neural network, or checkpoint loading.

Instead it:
  1) reads the pilot_sample.json produced by
     prepare_deepprotacs_pilot_sample.py;
  2) copies the five matched inputs into a clean staging directory using
     the exact filenames required by official DeepPROTACs;
  3) invokes the official DeepPROTACs single_prediction.py;
  4) captures the official 0/1 prediction;
  5) writes a reproducibility record including SHA256 hashes.

Official DeepPROTACs expects:
    ligase_ligand.mol2
    ligase_pocket.mol2
    target_ligand.mol2
    target_pocket.mol2
    linker.smi

Official repository:
    https://github.com/Fenglei104/DeepPROTACs

Important Windows portability note
----------------------------------
The official single_prediction.py contains four Linux-style shell commands:

    os.system("babel ... >/dev/null 2>&1")

Those lines are only an OpenBabel in-place preprocessing step. On Windows,
the '/dev/null' redirection is not portable, and modern OpenBabel normally
provides 'obabel' rather than the old 'babel' executable.

For --script-mode portable (default on Windows), this wrapper creates a
TEMPORARY COPY of official single_prediction.py and disables ONLY those four
shell preprocessing lines. All DeepPROTACs feature construction, vocabularies,
model loading, forward pass and class prediction remain the official code.

This is appropriate here because the five staged MOL2 files have already
been produced/preprocessed by OpenBabel in the TopoLinker docking pipeline.
The source MOL2 files are never modified.

For an original Linux DeepPROTACs environment with Babel 2.x, use:
    --script-mode exact

Default pilot manifest
----------------------
eval_outputs/deepprotacs_docking/deepprotacs_pilot_sample/
    rl2_record_0019/pilot_sample.json

Examples
--------
Preflight only:
    python evaluation/run_deepprotacs_pilot.py ^
        --deepprotacs-dir "D:\\path\\to\\DeepPROTACs" ^
        --preflight-only

Run with current Python:
    python evaluation/run_deepprotacs_pilot.py ^
        --deepprotacs-dir "D:\\path\\to\\DeepPROTACs"

Run with a dedicated DeepPROTACs conda environment:
    python evaluation/run_deepprotacs_pilot.py ^
        --deepprotacs-dir "D:\\path\\to\\DeepPROTACs" ^
        --deepprotacs-python "D:\\study\\Anaconda3\\envs\\DeepPROTACs\\python.exe"

Exact official script mode:
    python evaluation/run_deepprotacs_pilot.py ^
        --deepprotacs-dir "/path/to/DeepPROTACs" ^
        --script-mode exact

Outputs
-------
eval_outputs/deepprotacs_docking/deepprotacs_inference_pilot/
    rl2_record_0019/
        input/
            ligase_ligand.mol2
            ligase_pocket.mol2
            target_ligand.mol2
            target_pocket.mol2
            linker.smi
            data/processed/...     # generated by official DeepPROTACs
        official_single_prediction_portable.py  # portable mode only
        preflight_stdout.txt
        preflight_stderr.txt
        deepprotacs_stdout.txt
        deepprotacs_stderr.txt
        deepprotacs_pilot_result.json
        deepprotacs_pilot_result.csv
"""

