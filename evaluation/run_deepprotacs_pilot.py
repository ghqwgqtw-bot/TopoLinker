def dependency_preflight(
    python_exe: Path,
    repo: Path,
) -> subprocess.CompletedProcess:
    code = (
        "import sys, torch, rdkit, torch_geometric; "
        "print('python=' + sys.version.replace('\\n',' ')); "
        "print('torch=' + str(torch.__version__)); "
        "print('cuda_available=' + str(torch.cuda.is_available())); "
        "print('rdkit=' + str(getattr(rdkit,'__version__','unknown'))); "
        "print('torch_geometric=' + str(torch_geometric.__version__))"
    )

    env = os.environ.copy()
    env["PYTHONPATH"] = (
        str(repo)
        + os.pathsep
        + env.get("PYTHONPATH", "")
    )

    return run_cmd(
        [str(python_exe), "-c", code],
        cwd=repo,
        env=env,
        timeout=120,
    )


# =====================================================================
# Prediction parsing
# =====================================================================

def parse_official_prediction(stdout: str) -> int:
    """
    Official single_prediction.py ends with:
        print(pred_y)
    where pred_y is 0 or 1.

    Use the LAST standalone 0/1 line.
    """
    found: List[int] = []

    for line in stdout.splitlines():
        m = re.fullmatch(r"\s*([01])\s*", line)
        if m:
            found.append(int(m.group(1)))

    if not found:
        raise RuntimeError(
            "Could not find an official standalone 0/1 prediction "
            "in DeepPROTACs stdout."
        )

    return found[-1]


