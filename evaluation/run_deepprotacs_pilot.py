# Windows-portable temporary copy of official single_prediction.py
# =====================================================================

def create_portable_single_prediction(
    official_script: Path,
    patched_script: Path,
) -> int:
    """
    Disable ONLY the four old Babel shell preprocessing commands.

    No DeepPROTACs preprocessing/model/tokenizer/forward code is replaced.

    Returns number of disabled lines.
    """
    text = safe_read_text(official_script)
    out_lines: List[str] = []
    disabled = 0

    target_names = {
        "ligase_ligand.mol2",
        "ligase_pocket.mol2",
        "target_ligand.mol2",
        "target_pocket.mol2",
    }

    pyg_shim_inserted = False

    for line in text.splitlines():
        stripped = line.strip()

        is_babel_os_system = (
            "os.system(" in stripped
            and "babel " in stripped
            and any(name in stripped for name in target_names)
        )

        if is_babel_os_system:
            indent = line[: len(line) - len(line.lstrip())]
            out_lines.append(
                indent
                + "# [TopoLinker portable wrapper] "
                  "disabled non-portable Babel shell normalization"
            )
            disabled += 1
            continue

        # -----------------------------------------------------------------
        # Compatibility shim for the official full-object checkpoint.
        #
        # The public DeepPROTACs model/test.pt was serialized with an older
        # PyTorch-Geometric layout in which Inspector lived at:
        #
        #   torch_geometric.nn.conv.utils.inspector
        #
        # New PyG releases expose the same compatibility object from:
        #
        #   torch_geometric.inspector
        #
        # torch.load() needs the historical import path while unpickling.
        # We therefore register a temporary in-process module alias before
        # the official torch.load('model/test.pt') call.  This does NOT
        # change checkpoint tensors, DeepPROTACs architecture, graph
        # construction, SMILES encoding, or inference logic.
        # -----------------------------------------------------------------
        if (
            not pyg_shim_inserted
            and "torch.load(" in stripped
            and "model/test.pt" in stripped
        ):
            indent = line[: len(line) - len(line.lstrip())]

            shim = [
                indent + "# [TopoLinker portable wrapper] PyG legacy checkpoint compatibility shim",
                indent + "import sys as _tl_sys",
                indent + "import types as _tl_types",
                indent + "try:",
                indent + "    import torch_geometric.inspector as _tl_new_inspector",
                indent + "    import torch_geometric.nn.conv as _tl_conv_pkg",
                indent + "    from torch_geometric.inspector import Inspector as _tl_Inspector",
                indent + "    from torch_geometric.nn.conv.message_passing import MessagePassing as _tl_MessagePassing",
                indent + "    from torch_geometric.nn.resolver import aggregation_resolver as _tl_aggr_resolver",
                indent + "    from collections import OrderedDict as _tl_OrderedDict",
                indent + "",
                indent + "    # 1) Historical module-path alias needed by pickle.",
                indent + "    _tl_utils_name = 'torch_geometric.nn.conv.utils'",
                indent + "    _tl_inspector_name = _tl_utils_name + '.inspector'",
                indent + "    if _tl_utils_name in _tl_sys.modules:",
                indent + "        _tl_utils_pkg = _tl_sys.modules[_tl_utils_name]",
                indent + "    else:",
                indent + "        _tl_utils_pkg = _tl_types.ModuleType(_tl_utils_name)",
                indent + "        _tl_utils_pkg.__path__ = []",
                indent + "        _tl_sys.modules[_tl_utils_name] = _tl_utils_pkg",
                indent + "        setattr(_tl_conv_pkg, 'utils', _tl_utils_pkg)",
                indent + "    _tl_sys.modules[_tl_inspector_name] = _tl_new_inspector",
                indent + "    setattr(_tl_utils_pkg, 'inspector', _tl_new_inspector)",
                indent + "",
                indent + "    # 2) The old pickled Inspector object does not contain the",
                indent + "    #    modern '_cls' field. PyG 2.7 MessagePassing.__setstate__",
                indent + "    #    immediately calls _set_jittable_templates(), which then",
                indent + "    #    crashes on Inspector.implements(). Rebuild ONLY the",
                indent + "    #    Inspector metadata from the current layer class before",
                indent + "    #    delegating to the official/current __setstate__.",
                indent + "    _tl_orig_mp_setstate = _tl_MessagePassing.__setstate__",
                indent + "",
                indent + "    def _tl_compat_mp_setstate(self, data):",
                indent + "        _tl_data = dict(data)",
                indent + "",
                indent + "        # Rebuild current PyG Inspector metadata.",
                indent + "        _tl_insp = _tl_Inspector(self.__class__)",
                indent + "        _tl_insp.inspect_signature(self.message)",
                indent + "        _tl_insp.inspect_signature(self.aggregate, exclude=[0, 'aggr'])",
                indent + "        _tl_insp.inspect_signature(self.message_and_aggregate, [0])",
                indent + "        _tl_insp.inspect_signature(self.update, exclude=[0])",
                indent + "        _tl_insp.inspect_signature(self.edge_update)",
                indent + "        _tl_data['inspector'] = _tl_insp",
                indent + "",
                indent + "        # PyG 2.x MessagePassing stores aggregation as a registered",
                indent + "        # nn.Module named 'aggr_module'. Older full-object checkpoints",
                indent + "        # predate this field, so merge it into the old _modules dict",
                indent + "        # without touching the checkpoint's learned submodules/weights.",
                indent + "        _tl_modules = dict(_tl_data.get('_modules', {}))",
                indent + "        if 'aggr_module' not in _tl_modules:",
                indent + "            _tl_aggr = _tl_data.get('aggr', 'add')",
                indent + "            _tl_modules['aggr_module'] = _tl_aggr_resolver(_tl_aggr)",
                indent + "        _tl_data['_modules'] = _tl_modules",
                indent + "",
                indent + "        # Recompute runtime argument metadata expected by current PyG.",
                indent + "        _tl_data['_user_args'] = _tl_insp.get_flat_param_names(",
                indent + "            ['message', 'aggregate', 'update'],",
                indent + "            exclude=self.special_args)",
                indent + "        _tl_data['_fused_user_args'] = _tl_insp.get_flat_param_names(",
                indent + "            ['message_and_aggregate', 'update'],",
                indent + "            exclude=self.special_args)",
                indent + "        _tl_data['_edge_user_args'] = _tl_insp.get_param_names(",
                indent + "            'edge_update', exclude=self.special_args)",
                indent + "",
                indent + "        _tl_fuse = _tl_insp.implements('message_and_aggregate')",
                indent + "        _tl_aggr_value = _tl_data.get('aggr', None)",
                indent + "        if _tl_aggr_value is not None:",
                indent + "            _tl_fuse = _tl_fuse and isinstance(_tl_aggr_value, str) and _tl_aggr_value in {'add', 'sum', 'mean', 'min', 'max'}",
                indent + "        _tl_data['fuse'] = _tl_fuse",
                indent + "",
                indent + "        # Fill only missing runtime-only MessagePassing fields. These",
                indent + "        # are hooks/explainability/decomposition state, not learned",
                indent + "        # parameters.",
                indent + "        for _tl_key in [",
                indent + "            '_propagate_forward_pre_hooks', '_propagate_forward_hooks',",
                indent + "            '_message_forward_pre_hooks', '_message_forward_hooks',",
                indent + "            '_aggregate_forward_pre_hooks', '_aggregate_forward_hooks',",
                indent + "            '_message_and_aggregate_forward_pre_hooks',",
                indent + "            '_message_and_aggregate_forward_hooks',",
                indent + "            '_edge_update_forward_pre_hooks', '_edge_update_forward_hooks',",
                indent + "        ]:",
                indent + "            _tl_data.setdefault(_tl_key, _tl_OrderedDict())",
                indent + "        _tl_data.setdefault('_explain', None)",
                indent + "        _tl_data.setdefault('_edge_mask', None)",
                indent + "        _tl_data.setdefault('_loop_mask', None)",
                indent + "        _tl_data.setdefault('_apply_sigmoid', True)",
                indent + "        _tl_data.setdefault('_decomposed_layers', 1)",
                indent + "",
                indent + "        return _tl_orig_mp_setstate(self, _tl_data)",
                indent + "",
                indent + "    _tl_MessagePassing.__setstate__ = _tl_compat_mp_setstate",
                indent + "except Exception as _tl_exc:",
                indent + "    print('[TopoLinker] PyG legacy checkpoint shim failed: %r' % (_tl_exc,), file=sys.stderr)",
            ]
            out_lines.extend(shim)
            pyg_shim_inserted = True

        out_lines.append(line)

    if disabled != 4:
        raise RuntimeError(
            "Expected exactly 4 Babel preprocessing commands in official "
            f"single_prediction.py, but found {disabled}. "
            "The upstream file may have changed; refusing to patch silently."
        )

    if not pyg_shim_inserted:
        raise RuntimeError(
            "Could not locate torch.load('model/test.pt') in official "
            "single_prediction.py; refusing to add the PyG checkpoint "
            "compatibility shim silently."
        )

    patched_script.write_text(
        "\n".join(out_lines) + "\n",
        encoding="utf-8",
    )

    return disabled


